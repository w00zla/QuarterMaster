export type Lang = "de" | "en";
const system: Lang = navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
/** The UI language: the config's `language` ("de", "en"), else the system's. Reactive: templates
 * calling `t` follow a change. */
export const langRef = ref<Lang>(system);

/** Applies the config's language setting ("" = the system's). */
export function applyLangSetting(setting: string) {
  langRef.value = setting === "de" || setting === "en" ? setting : system;
}

export const isKey = (key: string): key is Key => key in en;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const dict = langRef.value === "de" ? de : en;
  return dict[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
