const TEXTS: Record<Lang, Record<Key, string>> = { de, en };

const browserLang: Lang = navigator.language.toLowerCase().startsWith("de") ? "de" : "en";

/** The effective language: the stored override, else the browser's (also on the login screen). */
export const lang = computed<Lang>(() => me.value?.langOverride ?? browserLang);

watch(lang, (l) => (document.documentElement.lang = l), { immediate: true });

export const isKey = (key: string): key is Key => key in en;

/** Text in the current language; `{name}` placeholders from vars. Reactive in templates. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return TEXTS[lang.value][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

